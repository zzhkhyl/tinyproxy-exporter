func TestParseStatsPageKnownFormats(t *testing.T) {
	tests := []struct {
		name string
		body string
		want map[string]float64
	}{
		{
			name: "custom machine readable template",
			body: customPage,
			want: map[string]float64{
				FieldOpenConnections:    3,
				FieldRequestsTotal:      142,
				FieldBadConnections:     0,
				FieldDeniedConnections:  2,
				FieldRefusedConnections: 1,
			},
		},
		{
			name: "shipped table template",
			body: tablePage,
			want: map[string]float64{
				FieldOpenConnections:    7,
				FieldRequestsTotal:      142,
				FieldBadConnections:     1,
				FieldDeniedConnections:  2,
				FieldRefusedConnections: 3,
			},
		},
		{
			name: "built in fallback page",
			body: builtinPage,
			want: map[string]float64{
				FieldOpenConnections:    4,
				FieldRequestsTotal:      99,
				FieldBadConnections:     5,
				FieldDeniedConnections:  1,
				FieldRefusedConnections: 6,
			},
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := ParseStatsPage([]byte(tc.body))
			for field, want := range tc.want {
				v, ok := got.Fields[field]
				if !ok {
					t.Fatalf("field %q missing, got %v", field, got.Fields)
				}
				if v != want {
					t.Fatalf("field %q = %v, want %v", field, v, want)
				}
			}
			if len(got.Fields) != len(tc.want) {
				t.Fatalf("unexpected extra fields: got %v want %v", got.Fields, tc.want)
			}
		})
	}
}

func TestParseStatsPageClampsBytesLabelsToCanonicalFields(t *testing.T) {
	// The order of the keyword rules matters: "refused" must win over
	// "connections" and "request", "bad"/"denied" over the generic wording.
	res := ParseStatsPage([]byte("Number of refused connections due to high load: 12\n"))
	if got := res.Fields[FieldRefusedConnections]; got != 12 {
		t.Fatalf("refused = %v, want 12 (fields: %v)", got, res.Fields)
	}
	if _, ok := res.Fields[FieldOpenConnections]; ok {
		t.Fatalf("refused must not be mistaken for open connections: %v", res.Fields)
	}
}

func TestParseStatsPageKeepsUnknownFieldsAsPassthrough(t *testing.T) {
	res := ParseStatsPage([]byte("tinyproxy_stathost_tls_handshakes_total 17\nsome future field 42\n"))
	if got := res.Raw["tinyproxy_stathost_tls_handshakes_total"]; got != 17 {
		t.Fatalf("raw passthrough missing: %v", res.Raw)
	}
	if got := res.Raw["some_future_field"]; got != 42 {
		t.Fatalf("raw passthrough missing the future field: %v", res.Raw)
	}
	if len(res.Fields) != 0 {
		t.Fatalf("unknown labels must not become canonical fields: %v", res.Fields)
	}
}

func TestParseStatsPageReadsTextFields(t *testing.T) {
	res := ParseStatsPage([]byte(customPage))
	if got := res.Text[TextFieldVersion]; got != "1.11.3" {
		t.Fatalf("version = %q, want 1.11.3", got)
	}
	if got := res.Text[TextFieldPackage]; got != "tinyproxy" {
		t.Fatalf("package = %q, want tinyproxy", got)
	}
}

func TestParseStatsPageIgnoresUnsubstitutedPlaceholders(t *testing.T) {
	// tinyproxy leaves {unknownvar} untouched when a variable is not defined.
	res := ParseStatsPage([]byte("tinyproxy_stathost_open_connections {opens}\ntinyproxy_stathost_requests_total 5\n"))
	if len(res.Fields) != 1 {
		t.Fatalf("expected only the substituted field, got %v", res.Fields)
	}
	if got := res.Fields[FieldRequestsTotal]; got != 5 {
		t.Fatalf("requests = %v, want 5", got)
	}
}

func TestParseStatsPageHandlesEmptyAndGarbageInput(t *testing.T) {
	for _, body := range []string{"", "   \n\n", "<html><body></body></html>", "not a statistics page at all"} {
		res := ParseStatsPage([]byte(body))
		if len(res.Fields) != 0 {
			t.Fatalf("body %q produced fields %v", body, res.Fields)
		}
	}
}

func TestStatsResultRawMirrorsEveryNumericLabel(t *testing.T) {
	res := ParseStatsPage([]byte(customPage))
	if len(res.Raw) < 5 {
		t.Fatalf("expected the raw mirror to hold at least 5 entries, got %v", res.Raw)
	}
	if got := res.Raw["tinyproxy_stathost_open_connections"]; got != 3 {
		t.Fatalf("raw open connections = %v, want 3", got)
	}
}

func TestResetTrackerKeepsCountersMonotonic(t *testing.T) {
	tr := &resetTracker{}

	if got := tr.accumulate(10); got != 10 {
		t.Fatalf("first sample = %v, want 10", got)
	}
	if got := tr.accumulate(25); got != 25 {
		t.Fatalf("second sample = %v, want 25", got)
	}
	// tinyproxy restarted and the counter dropped back.
	if got := tr.accumulate(3); got != 28 {
		t.Fatalf("after restart = %v, want 28", got)
	}
	if got := tr.accumulate(9); got != 34 {
		t.Fatalf("after restart, growing = %v, want 34", got)
	}
	if math.IsNaN(tr.accumulate(0)) {
		t.Fatal("tracker produced NaN")
	}
}

func TestSanitizeLabelProducesPrometheusSafeValues(t *testing.T) {
	tests := map[string]string{
		"Open connections":                  "open_connections",
		"Number of refused connections ...": "number_of_refused_connections",
		"  spaced  out  ":                   "spaced_out",
		"":                                  "",
	}
	for in, want := range tests {
		if got := sanitizeLabel(in); got != want {
			t.Fatalf("sanitizeLabel(%q) = %q, want %q", in, got, want)
		}
	}
}
